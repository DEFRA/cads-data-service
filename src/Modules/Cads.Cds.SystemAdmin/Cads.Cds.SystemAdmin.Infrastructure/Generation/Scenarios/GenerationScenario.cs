namespace Cads.Cds.SystemAdmin.Infrastructure.Generation.Scenarios;

public abstract class GenerationScenario<T>(string name,
    ImportActionType importActionType,
    DbContext dbContext,
    IFileNameGenerator fileNameGenerator,
    IFileAssembler fileAssembler) : IGenerationScenario
    where T : class, new()
{
    public string Name { get; init; } = name;

    public string TableName { get; init; } = dbContext.GetTableName<T>();

    public ImportActionType ImportActionType { get; init; } = importActionType;

    protected virtual RuleBuilder<T>? OverrideRulesBuilder { get; init; }

    protected virtual Func<ICreateGenerationRequest, T, decimal, T>? Transform { get; init; }

    protected virtual IReadOnlyDictionary<string, ColumnDefinition> ColumnDefinitions => EntityExtensions.ResolveColumnDefinitions<T>();

    protected virtual IReadOnlyDictionary<string, ColumnDefinition> OverrideColumnDefinitions(IReadOnlyDictionary<string, ColumnDefinition> defaultColumnDefinitions)
    {
        return defaultColumnDefinitions;
    }

    public async Task<CreateGenerationResponseDto> ExecuteAsync(ICreateGenerationRequest request, CancellationToken ct = default)
    {
        ct.ThrowIfCancellationRequested();

        // Additional validation to ensure that the request is appropriate for the scenario type
        ValidateRequest(request);

        var contentGenerator = new ContentGenerator<T>(dbContext, OverrideRulesBuilder, Transform, [.. OverrideColumnDefinitions(ColumnDefinitions).Select(x => x.Value)]);

        // Bulk request must be validated to ensure that business keys are generated by the allocator.
        if (ImportActionType == ImportActionType.Bulk)
        {
            request.BusinessKeys = await new BusinessKeysAllocator().AllocateAsync(TableName, request.RowCount.GetValueOrDefault(), ct);
        }

        /*
        TODO: LANI-849 had this so it could be regenerated. Need to fulfil the requirements from LANI-849.
        */
        var seed = Random.Shared.Next();
        var rows = contentGenerator.Generate(request, seed);

        var fileBatchId = Random.Shared
            .Next(CtsmFilenameGenerator.MinBatchId, CtsmFilenameGenerator.MaxBatchId + 1)
            .ToString("D5", CultureInfo.InvariantCulture);

        var fileCreatedDateTime = DateTime.UtcNow;
        var fileName = fileNameGenerator.Create(
            new CreateFileNameCommand
            {
                App = CtsmFilenameGenerator.App,
                Env = CtsmFilenameGenerator.Env,
                Type = ImportActionType,
                BatchId = fileBatchId,
                TableName = TableName,
                Timestamp = fileCreatedDateTime
            });

        var parsedFileName = CtsmFilenameParser.Parse(fileName);

        var content = fileAssembler.Create(fileName, fileCreatedDateTime, rows);

        return new CreateGenerationResponseDto
        {
            FileName = fileName,
            GroupKey = parsedFileName!.GetGroupKey(),
            Content = content,
            BusinessKeys = [.. request.BusinessKeys!],
        };
    }

    private void ValidateRequest(ICreateGenerationRequest request)
    {
        switch (ImportActionType)
        {
            case ImportActionType.Bulk:

                if (request.BusinessKeys is not null)
                {
                    throw new ArgumentException("Business keys should not be provided for a bulk scenario.");
                }

                if (!request.RowCount.HasValue)
                {
                    throw new GenerationValidationException("Row count is required for a bulk scenario.");
                }

                if (request.RowCount is not > 0)
                {
                    throw new GenerationValidationException("Row count must be greater than zero for a bulk scenario.");
                }

                break;

            case ImportActionType.Delta:

                if (request.RowCount.HasValue)
                {
                    throw new GenerationValidationException("Row count should not be provided for a delta scenario.");
                }

                if (request.BusinessKeys is null || !request.BusinessKeys.Any())
                {
                    throw new ArgumentException("Business keys must be provided for a delta scenario.");
                }

                break;

            default:
                throw new NotSupportedException($"Import action type '{ImportActionType}' is not supported.");
        }
    }
}